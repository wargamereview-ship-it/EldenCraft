"""Minecraft-style art for the Elden Ring items (no game assets).

Every icon is 16x16 in two layers: a grey "tint" layer that Minecraft colours per item (the item's
custom_model_data colour, picked from its name or infusion by tools/generate_items.py) and a fixed
layer on top (outlines, handles, gold fittings). Weapons are drawn along the diagonal like Minecraft's
tools; the rest come from pixel masks. Also writes the item model definitions, the models and the
worn armour textures (dyeable, so each set takes its own colour).
"""
