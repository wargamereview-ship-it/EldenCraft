def armour_texture(weight, leggings):
    """A 64x32 humanoid armour layer in greys (dyed per set): plates, trims and rivets by weight class."""
    img = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    base = {"light": 150, "medium": 170, "heavy": 190}[weight]

    def box(x, y, w, h, d, pattern):
        # Minecraft's box UV layout: top/bottom then the four sides.
        faces = [(x + d, y, w, d), (x + d + w, y, w, d), (x, y + d, d, h), (x + d, y + d, w, h), (x + d + w, y + d, d, h), (x + d + w + d, y + d, w, h)]
        for fx, fy, fw, fh in faces:
            for py in range(fh):
                for px in range(fw):
                    img.putpixel((fx + px, fy + py), pattern(px, py, fw, fh))

    def plate(px, py, w, h):
        v = base
        if px in (0, w - 1) or py in (0, h - 1):
            v -= 45
        elif weight == "heavy" and py % 4 == 0:
            v -= 25
        elif weight == "medium" and (px + py) % 6 == 0:
            v -= 18
        elif weight == "light" and py % 3 == 0:
            v -= 12
        if weight != "light" and px in (1, w - 2) and py in (1, h - 2):
            v = 235
        return (v, v, v, 255)

    if leggings:
        box(16, 16, 8, 12, 4, plate)       # body (waist)
        box(0, 16, 4, 12, 4, plate)        # legs
    else:
        box(0, 0, 8, 8, 8, plate)          # head
        box(16, 16, 8, 12, 4, plate)       # body
        box(40, 16, 4, 12, 4, plate)       # arms
        box(0, 16, 4, 12, 4, plate)        # legs (boots)
    return img


def main():
    for w in WEAPONS:
        save(weapon(w), ASSETS / "textures/item/er/weapon" / w)
        model("weapon", w, w not in ("small_shield", "medium_shield", "greatshield", "thrusting_shield", "seal", "fist", "claw",
                                     "perfume_bottle"))
    for slot in ("helm", "chest", "gauntlets", "legs"):
        for weight in ("light", "medium", "heavy"):
            save(mask(f"{slot}_{weight}"), ASSETS / "textures/item/er/armour" / f"{slot}_{weight}")
            model("armour", f"{slot}_{weight}", False)
    save(mask("talisman"), ASSETS / "textures/item/er/misc/talisman")
    model("misc", "talisman", False)
    for name in GOODS:
        save(mask(name) if name in MASKS else weapon(name), ASSETS / "textures/item/er/goods" / name)
        model("goods", name, False)
    for weight in ("light", "medium", "heavy"):
        for layer, leggings in (("humanoid", False), ("humanoid_leggings", True)):
            path = ASSETS / f"textures/entity/equipment/{layer}/er_{weight}.png"
            path.parent.mkdir(parents=True, exist_ok=True)
            armour_texture(weight, leggings).save(path)
        dyed = {"dyeable": {"color_when_undyed": -1}}
        (ASSETS / "equipment").mkdir(parents=True, exist_ok=True)
        (ASSETS / f"equipment/er_{weight}.json").write_text(json.dumps({"layers": {
            "humanoid": [{"texture": f"eldencraft:er_{weight}", **dyed}],
            "humanoid_leggings": [{"texture": f"eldencraft:er_{weight}", **dyed}]}}, indent=2) + "\n")
    (ASSETS / "equipment/er_hidden.json").write_text(json.dumps({"layers": {}}, indent=2) + "\n")
    # Plain fallback models for the registered items themselves (stacks always carry their own item_model).
    for item, art in (("er_weapon", "weapon/straight_sword"), ("er_bow", "weapon/bow"), ("er_crossbow", "weapon/crossbow"),
                      ("er_ammo", "weapon/arrow"), ("er_shield", "weapon/medium_shield"), ("er_catalyst", "weapon/staff"),
                      ("er_armour", "armour/chest_medium"), ("er_talisman", "misc/talisman"), ("er_goods", "goods/consumable"),
                      ("er_ash", "goods/ash_of_war")):
        (ASSETS / f"items/{item}.json").write_text(json.dumps({"model": {"type": "minecraft:model", "model": f"eldencraft:item/er/{art}",
            "tints": [{"type": "minecraft:constant", "value": -6710887}, {"type": "minecraft:constant", "value": -1}]}}, indent=2) + "\n")
    print(f"art: {len(WEAPONS)} weapon classes, 12 armour icons, {len(GOODS)} goods, 3 worn armour weights")


if __name__ == "__main__":
    main()
