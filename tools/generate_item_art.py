def mask(name):
    rows = [r for r in MASKS[name].strip("\n").split("\n")]
    g = blank()
    top = (16 - len(rows)) // 2
    for y, row in enumerate(rows):
        for x, c in enumerate(row[:16]):
            put(g, x, top + y, c)
    return g


def save(grid, path_base):
    tint = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    fixed = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y in range(16):
        for x in range(16):
            c = grid[y][x]
            if c in TINT:
                v = TINT[c]
                tint.putpixel((x, y), (v, v, v, 255))
            elif c in FIXED:
                fixed.putpixel((x, y), FIXED[c] + (255,))
    path_base.parent.mkdir(parents=True, exist_ok=True)
    tint.save(str(path_base) + "_tint.png")
    fixed.save(str(path_base) + ".png")


def model(group, name, handheld):
    tex = f"eldencraft:item/er/{group}/{name}"
    (ASSETS / "models/item/er" / group).mkdir(parents=True, exist_ok=True)
    (ASSETS / "models/item/er" / group / f"{name}.json").write_text(json.dumps({
        "parent": "minecraft:item/handheld" if handheld else "minecraft:item/generated",
        "textures": {"layer0": tex + "_tint", "layer1": tex}}, indent=2) + "\n")
    path = ASSETS / "items/er" / (f"{group}/{name}.json" if group != "." else f"{name}.json")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"model": {"type": "minecraft:model", "model": f"eldencraft:item/er/{group}/{name}",
        "tints": [{"type": "minecraft:custom_model_data", "index": 0, "default": -1}, {"type": "minecraft:constant", "value": -1}]}},
        indent=2) + "\n")


